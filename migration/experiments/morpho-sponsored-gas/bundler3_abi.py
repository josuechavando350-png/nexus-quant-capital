"""Research-only ABI v2 encoder for Morpho Bundler3 Call[] and nested reentry.

Source: morpho-org/bundler3@b4014349e3527f44ceaab697b26e29f2b11457f3
Does not sign, send, price, approve live assets, or assert builder acceptance.
The generated bytes require independent Solidity/Foundry differential parity and a
complete, economically proven call path before any transaction is permissible.
"""
from __future__ import annotations

from dataclasses import dataclass
from evm_hash import keccak256 as keccak

MAX = 2**256 - 1


def _word(n: object) -> bytes:
    if type(n) is not int or not (0 <= n <= MAX):
        raise ValueError("uint256 word out of range")
    return n.to_bytes(32, "big")


def _address(s: object) -> bytes:
    if not isinstance(s, str) or len(s) != 42 or not s.startswith("0x"):
        raise ValueError("bad EVM address")
    try:
        out = bytes.fromhex(s[2:])
    except ValueError as exc:
        raise ValueError("bad address hex") from exc
    if len(out) != 20:
        raise ValueError("address hex must encode exactly 20 bytes without whitespace")
    if out == bytes(20):
        raise ValueError("zero address")
    return out.rjust(32, b"\0")


def selector(signature: str) -> bytes:
    return keccak(signature.encode())[:4]


def dynamic_bytes(data: bytes) -> bytes:
    if not isinstance(data, bytes):
        raise ValueError("data must be bytes")
    return _word(len(data)) + data + bytes((-len(data)) % 32)


@dataclass(frozen=True)
class Call:
    to: str
    data: bytes
    value: int = 0
    skip_revert: bool = False
    callback_hash: bytes = bytes(32)

    def encode_tuple(self) -> bytes:
        if type(self.skip_revert) is not bool or self.skip_revert:
            raise ValueError("research requires skipRevert=false")
        if not isinstance(self.callback_hash, bytes) or len(self.callback_hash) != 32:
            raise ValueError("bad callback hash")
        # Static tuple head: address, bytes offset, value, bool, bytes32.
        return (_address(self.to) + _word(5*32) + _word(self.value) + _word(0)
                + self.callback_hash + dynamic_bytes(self.data))


def encode_call_array(calls: tuple[Call, ...]) -> bytes:
    if not isinstance(calls, tuple) or not calls:
        raise ValueError("non-empty immutable Call tuple required")
    elements = [x.encode_tuple() for x in calls]
    offset = len(calls)*32
    heads = []
    for encoded in elements:
        heads.append(_word(offset))
        offset += len(encoded)
    return _word(len(calls)) + b"".join(heads) + b"".join(elements)


def abi_encode_calls(calls: tuple[Call, ...]) -> bytes:
    """ABI encodes the single *dynamic* argument Call[] (offset + array data)."""
    return _word(32) + encode_call_array(calls)


def multicall_calldata(calls: tuple[Call, ...]) -> bytes:
    return selector("multicall((address,bytes,uint256,bool,bytes32)[])") + abi_encode_calls(calls)


def flashloan_callback_hash(nested_calls: tuple[Call, ...]) -> bytes:
    """Hash of the bytes appended after reenter(Call[])'s 4-byte selector."""
    return keccak(abi_encode_calls(nested_calls))


def adapter_flashloan_calldata(token: str, amount: int, nested_calls: tuple[Call, ...]) -> bytes:
    # Morpho GeneralAdapter1.morphoFlashLoan(address,uint256,bytes)
    callback_data = abi_encode_calls(nested_calls)
    return (selector("morphoFlashLoan(address,uint256,bytes)") +
            _address(token) + _word(amount) + _word(96) + dynamic_bytes(callback_data))


def encode_flashloan_top_call(adapter: str, token: str, amount: int,
                               nested_calls: tuple[Call, ...]) -> Call:
    return Call(to=adapter, data=adapter_flashloan_calldata(token, amount, nested_calls),
                callback_hash=flashloan_callback_hash(nested_calls))


def erc20_approve(spender: str, amount: int) -> bytes:
    return selector("approve(address,uint256)") + _address(spender) + _word(amount)


def adapter_erc20_transfer(token: str, recipient: str, amount: int) -> bytes:
    return (selector("erc20Transfer(address,address,uint256)")
            + _address(token) + _address(recipient) + _word(amount))


def morpho_liquidate_no_callback(loan: str, collateral: str, oracle: str, irm: str,
                                  lltv: int, borrower: str, repay_shares: int) -> bytes:
    if not 0 < repay_shares <= MAX or not 0 < lltv < 10**18:
        raise ValueError("invalid Morpho liquidation parameters")
    # Struct MarketParams is a STATIC tuple with 5 words.
    # Final bytes data is dynamic, offset 9*32 and contains empty bytes.
    return (selector("liquidate((address,address,address,address,uint256),address,uint256,uint256,bytes)")
            + _address(loan) + _address(collateral) + _address(oracle) + _address(irm)
            + _word(lltv) + _address(borrower) + _word(0) + _word(repay_shares)
            + _word(9*32) + dynamic_bytes(b""))
